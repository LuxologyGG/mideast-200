// Builds src/generated/geo.js: a projected basemap (Natural Earth 1:50m land and lakes, 1:10m rivers; public domain)
// plus screen positions for every lesson pin and Map Quiz location.
// Usage: node scripts/build-basemap.mjs [dir-with-natural-earth-geojson]
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import {geoConicEqualArea, geoGraticule, geoPath} from 'd3-geo';
import {PLACES, QUIZ} from '../src/content/places.js';

const dir = process.argv[2] || '/home/claude/ne';
const NE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/';
async function layer(name) {
  const local = `${dir}/${name}.geojson`;
  if (existsSync(local)) return JSON.parse(readFileSync(local, 'utf8'));
  const res = await fetch(NE + name + '.geojson');
  return res.json();
}

const W = 1000;
const LON = [8, 78], LAT = [9, 46.5];
const frame = [];
for (let x = LON[0]; x <= LON[1]; x += 1) frame.push([x, LAT[0]], [x, LAT[1]]);
for (let y = LAT[0]; y <= LAT[1]; y += 0.5) frame.push([LON[0], y], [LON[1], y]);
const projection = geoConicEqualArea().parallels([20, 40]).rotate([-43, 0]).fitWidth(W, {type: 'MultiPoint', coordinates: frame});
const bounds = geoPath(projection).bounds({type: 'MultiPoint', coordinates: frame});
const H = Math.ceil(bounds[1][1]);
projection.clipExtent([[-2, -2], [W + 2, H + 2]]);
const path = geoPath(projection).digits(1);

// Drop points closer than tol px to the last kept point, ring by ring.
function simplify(d, tol = 0.9) {
  if (!d) return '';
  const out = [];
  for (const ring of d.split(/(?=M)/)) {
    const closed = ring.endsWith('Z');
    const pts = ring.replace(/[MZ]/g, '').split('L').map(p => p.split(',').map(Number)).filter(p => p.length === 2 && !p.some(Number.isNaN));
    if (pts.length < 2) continue;
    const kept = [pts[0]];
    for (let i = 1; i < pts.length - 1; i++) {
      const [x, y] = pts[i], [lx, ly] = kept[kept.length - 1];
      if (Math.hypot(x - lx, y - ly) >= tol) kept.push(pts[i]);
    }
    kept.push(pts[pts.length - 1]);
    if (closed && kept.length < 4) continue;
    out.push('M' + kept.map(p => p.map(v => Math.round(v * 10) / 10).join(',')).join('L') + (closed ? 'Z' : ''));
  }
  return out.join('');
}

const land = await layer('ne_50m_land');
const lakes = await layer('ne_50m_lakes');
const rivers = await layer('ne_10m_rivers_lake_centerlines');

// Course-list rivers first; the rest are drawn lighter for context. Natural Earth splits some rivers by local name.
const RIVERS = {
  Tigris: ['Tigris', 'Dicle', 'Shatt al Arab'], Euphrates: ['Euphrates', 'Al Furat', 'Firat'], Nile: ['Nile'], 'Amu Darya': ['Amu  Darya'], Indus: ['Indus'],
  'Syr Darya': ['Syr  Darya'], Jordan: ['Jordan'], Atbara: ['Atbara'], Helmand: ['Helmand'], Kura: ['Kura'], Aras: ['Aras'], Murat: ['Murat'],
  Karkheh: ['Karkheh'], Zarafshon: ['Zarafshon'], 'Qezel Owzan': ['Qezel Owzan']
};
const riverPaths = {};
const riverCoords = {};
for (const [name, parts] of Object.entries(RIVERS)) {
  const feats = rivers.features.filter(f => parts.includes(f.properties.name));
  riverPaths[name] = simplify(path({type: 'FeatureCollection', features: feats}), 0.7);
  riverCoords[name] = feats.flatMap(f => f.geometry.type === 'LineString' ? f.geometry.coordinates : f.geometry.coordinates.flat());
}

const xy = ll => {const p = projection(ll); return [Math.round(p[0] * 10) / 10, Math.round(p[1] * 10) / 10];};
const places = Object.fromEntries(Object.entries(PLACES).map(([k, ll]) => [k, xy(ll)]));
const quiz = Object.fromEntries(QUIZ.map(q => {
  let at = q.at;
  if (q.river && riverCoords[q.river]?.length) {
    const k = Math.cos(at[1] * Math.PI / 180);
    at = riverCoords[q.river].reduce((best, c) => (((c[0] - q.at[0]) * k) ** 2 + (c[1] - q.at[1]) ** 2) < (((best[0] - q.at[0]) * k) ** 2 + (best[1] - q.at[1]) ** 2) ? c : best);
  }
  return [q.id, xy(at)];
}));

const out = {
  w: W, h: H,
  land: simplify(path(land)),
  lakes: simplify(path(lakes), 0.7),
  rivers: riverPaths,
  graticule: simplify(path(geoGraticule().step([10, 10])()), 2),
  places, quiz
};
mkdirSync(new URL('../src/generated/', import.meta.url), {recursive: true});
writeFileSync(new URL('../src/generated/geo.js', import.meta.url),
  '// Generated by scripts/build-basemap.mjs from Natural Earth 1:50m data (public domain). Do not edit by hand.\n' +
  `export const GEO = ${JSON.stringify(out)};\n`);
